func (h *pgHarness) catalog(id string, request protocol.CatalogRequest) protocol.Response {
	h.t.Helper()
	command := protocol.Command{Type: "catalog", RequestID: h.id(), SessionID: id, QueryID: h.id(), Catalog: &request}
	h.send(command)
	started := h.receive()
	if started.Type != "query.started" || started.RequestID != command.RequestID || started.QueryID != command.QueryID || started.SessionID != id {
		h.t.Fatal("catalog did not publish a correlated start event")
	}
	response := h.receive()
	if response.RequestID != command.RequestID || response.QueryID != command.QueryID || response.SessionID != id || (response.Type != "query.result" && response.Type != "error") {
		h.t.Fatal("catalog did not return one correlated terminal reply")
	}
	return response
}

func catalogCell(t *testing.T, response protocol.Response, row int, column string) *string {
	t.Helper()
	for _, field := range response.Columns {
		if field.Name == column && row < len(response.Rows) && field.Index < len(response.Rows[row]) {
			return response.Rows[row][field.Index]
		}
	}
	t.Fatalf("catalog field %q or its row is missing", column)
	return nil
}

func catalogText(t *testing.T, response protocol.Response, row int, column string) string {
	t.Helper()
	value := catalogCell(t, response, row, column)
	if value == nil {
		t.Fatalf("catalog field %q is unexpectedly NULL", column)
	}
	return *value
}

func catalogFind(t *testing.T, response protocol.Response, name string) int {
	t.Helper()
	if response.Type != "query.result" {
		t.Fatalf("catalog did not return a result: category=%q state=%q", response.Category, response.SQLState)
	}
	for index := range response.Rows {
		if catalogText(t, response, index, "name") == name {
			return index
		}
	}
	t.Fatal("expected catalog object is missing")
	return -1
}

func TestPostgresCatalogObjectsDefinitionsAndQuotedBrowse(t *testing.T) {
	h := newPGHarness(t)
	schema := fmt.Sprintf("dbeer_catalog_%d", time.Now().UnixNano())
	object := `quoted "table';%_--`
	role := fmt.Sprintf("dbeer_catalog_reader_%d", time.Now().UnixNano())
	qualified := func(name string) string { return pgx.Identifier{schema, name}.Sanitize() }
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	exec := func(sql string) {
		t.Helper()
		if _, err := h.observer.Exec(ctx, sql); err != nil {
			t.Fatal("cannot create disposable PostgreSQL catalog fixture")
		}
	}
	exec("CREATE SCHEMA " + pgx.Identifier{schema}.Sanitize())
	t.Cleanup(func() {
		h.manager.Close()
		cleanupCtx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
		defer cancel()
		_, _ = h.observer.Exec(cleanupCtx, "DROP SCHEMA IF EXISTS "+pgx.Identifier{schema}.Sanitize()+" CASCADE")
		_, _ = h.observer.Exec(cleanupCtx, "DROP ROLE IF EXISTS "+pgx.Identifier{role}.Sanitize())
	})
	exec("CREATE TABLE " + qualified("parent") + " (tenant integer PRIMARY KEY)")
	exec("CREATE TABLE " + qualified(object) + ` (tenant integer NOT NULL REFERENCES ` + qualified("parent") + ` (tenant),
 id bigint GENERATED BY DEFAULT AS IDENTITY, marker text NOT NULL DEFAULT 'seed', nullable text,
 doubled integer GENERATED ALWAYS AS (tenant*2) STORED, PRIMARY KEY(tenant,id), UNIQUE(marker), CHECK(marker<>''))`)
	exec("CREATE INDEX " + pgx.Identifier{"fixture_marker_index"}.Sanitize() + " ON " + qualified(object) + "(lower(marker))")
	exec("INSERT INTO " + qualified("parent") + " VALUES(1)")
	exec("INSERT INTO " + qualified(object) + "(tenant,id,marker) SELECT 1,n,'marker-'||n FROM generate_series(1,205)n")
	exec("CREATE VIEW " + qualified("fixture_view") + " AS SELECT tenant,id,marker FROM " + qualified(object))
	exec("CREATE FUNCTION " + qualified("overloaded") + "(integer) RETURNS integer LANGUAGE sql AS 'SELECT $1+1'")
	exec("CREATE FUNCTION " + qualified("overloaded") + "(text) RETURNS text LANGUAGE sql AS 'SELECT $1'")
	exec("CREATE PROCEDURE " + qualified("fixture_procedure") + "() LANGUAGE plpgsql AS $$BEGIN NULL; END$$")
	exec("CREATE FUNCTION " + qualified("fixture_trigger_fn") + "() RETURNS trigger LANGUAGE plpgsql AS $$BEGIN RETURN NEW; END$$")
	exec("CREATE TRIGGER fixture_trigger BEFORE UPDATE ON " + qualified(object) + " FOR EACH ROW EXECUTE FUNCTION " + qualified("fixture_trigger_fn") + "()")
	service, sqlSession, data := h.connect(), h.connect(), h.connect()
	response := h.catalog(service, protocol.CatalogRequest{Kind: "schemas"})
	catalogFind(t, response, schema)
	response = h.catalog(service, protocol.CatalogRequest{Kind: "completion", Schema: schema})
	row := catalogFind(t, response, object)
	var completionColumns []string
	if json.Unmarshal([]byte(catalogText(t, response, row, "columns")), &completionColumns) != nil || strings.Join(completionColumns, ",") != "tenant,id,marker,nullable,doubled" {
		t.Fatal("completion snapshot lost column names or their order")
	}
	catalogFind(t, response, "fixture_view")
	catalogFind(t, response, "overloaded")
	// Pagination must retain deterministic ordering and keep identifiers in
	// parameters, even when a schema name resembles SQL.
	if empty := h.catalog(service, protocol.CatalogRequest{Kind: "completion", Schema: schema, Page: 1}); len(empty.Rows) != 0 {
		t.Fatal("completion page repeated objects")
	}
	if empty := h.catalog(service, protocol.CatalogRequest{Kind: "completion", Schema: "' OR 1=1 --"}); len(empty.Rows) != 0 {
		t.Fatal("completion schema was interpreted as SQL")
	}
	for _, kind := range []string{"table", "view", "function", "procedure", "trigger"} {
		response := h.catalog(service, protocol.CatalogRequest{Kind: "objects", Schema: schema, ObjectKind: kind})
		if response.Type != "query.result" || len(response.Rows) == 0 {
			t.Fatalf("catalog did not list %s objects: category=%q state=%q", kind, response.Category, response.SQLState)
		}
		identities := make(map[string]bool)
		for row := range response.Rows {
			identity := catalogText(t, response, row, "identity")
			if identity == "" || identities[identity] || catalogText(t, response, row, "kind") != kind || catalogText(t, response, row, "schema") != schema {
				t.Fatal("catalog omitted a distinct object identity or namespace")
			}
			identities[identity] = true
			definition := h.catalog(service, protocol.CatalogRequest{Kind: "definition", Schema: schema, Object: catalogText(t, response, row, "name"), ObjectKind: kind, Identity: identity})
			if definition.Type != "query.result" || len(definition.Rows) != 1 {
				t.Fatalf("catalog definition is unavailable for %s: category=%q state=%q", kind, definition.Category, definition.SQLState)
			}
			if kind != "table" && catalogText(t, definition, 0, "definition") == "" {
				t.Fatal("available object definition was empty")
			}
		}
	}
	response = h.catalog(service, protocol.CatalogRequest{Kind: "columns", Schema: schema, Object: object})
	if len(response.Rows) != 5 {
		t.Fatal("catalog did not retain all columns in their table order")
	}
	if catalogText(t, response, 0, "name") != "tenant" || catalogText(t, response, 0, "primaryKey") != "1" || catalogText(t, response, 1, "primaryKey") != "2" || catalogText(t, response, 2, "primaryKey") != "0" || catalogText(t, response, 2, "nullable") != "false" || catalogCell(t, response, 2, "default") == nil || catalogText(t, response, 4, "generated") == "" || catalogText(t, response, 4, "editable") != "false" {
		t.Fatal("catalog lost composite PK, nullable, default or generated column metadata")
	}
	for _, kind := range []string{"keys", "indexes", "constraints", "triggers"} {
		response := h.catalog(service, protocol.CatalogRequest{Kind: kind, Schema: schema, Object: object})
		if response.Type != "query.result" || len(response.Rows) == 0 || catalogText(t, response, 0, "definition") == "" || catalogText(t, response, 0, "kind") == "" {
			t.Fatalf("catalog did not expose %s: category=%q state=%q", kind, response.Category, response.SQLState)
		}
	}
	response = h.catalog(service, protocol.CatalogRequest{Kind: "search", Schema: schema, Search: "%_"})
	if len(response.Rows) != 1 || catalogText(t, response, 0, "name") != object {
		t.Fatal("catalog search treated wildcard characters as a pattern")
	}
	response = h.catalog(service, protocol.CatalogRequest{Kind: "select", Schema: schema, Object: object, ObjectKind: "table"})
	if catalogText(t, response, 0, "sql") != "SELECT * FROM "+qualified(object)+" LIMIT 200" || catalogText(t, response, 0, "name") != qualified(object) {
		t.Fatal("generated SQL did not quote the identifier inside the adapter")
	}
	// The metadata service and separate data session keep working while user SQL
	// owns a long-running connection. Browsing does not share that transaction.
	query := h.start(sqlSession, "SELECT pg_sleep(20)")
	response = h.catalog(data, protocol.CatalogRequest{Kind: "browse", Schema: schema, Object: object, ObjectKind: "table"})
	if response.Type != "query.result" || len(response.Rows) != 200 || response.RowCount != 200 || len(response.Columns) != 5 {
		t.Fatal("catalog browse did not return exactly the first 200 rows")
	}
	response = h.catalog(service, protocol.CatalogRequest{Kind: "objects", Schema: schema, ObjectKind: "function"})
	if len(response.Rows) != 3 {
		t.Fatal("slow SQL blocked catalog or an overloaded function disappeared")
	}
	h.send(protocol.Command{Type: "cancel", RequestID: h.id(), SessionID: sqlSession, QueryID: query.QueryID})
	for range 2 {
		response := h.receive()
		if response.Type != "cancel.ack" && (response.RequestID != query.RequestID || response.Category != "cancelled") {
			t.Fatal("catalog traffic interfered with SQL cancellation")
		}
	}
	// A restricted role simulates one inaccessible branch. Its failure leaves
	// the service session and all other connections usable.
	exec("CREATE ROLE " + pgx.Identifier{role}.Sanitize())
	h.query(service, "SET ROLE "+pgx.Identifier{role}.Sanitize(), "idle")
	response = h.catalog(service, protocol.CatalogRequest{Kind: "completion", Schema: schema})
	if response.Type != "query.result" || len(response.Rows) != 0 {
		t.Fatal("completion disclosed inaccessible objects")
	}
	response = h.catalog(service, protocol.CatalogRequest{Kind: "columns", Schema: schema, Object: object})
	if response.Type != "error" || response.SQLState != "42501" || !response.Connected || response.Message != "Catalog information is unavailable or access was denied." {
		t.Fatal("an inaccessible metadata branch was silently presented as empty")
	}
	response = h.catalog(service, protocol.CatalogRequest{Kind: "browse", Schema: schema, Object: object, ObjectKind: "table"})
	if response.Type != "error" || response.SQLState != "42501" || !response.Connected || response.Message != "Catalog information is unavailable or access was denied." || strings.Contains(response.Message, object) {
		t.Fatal("an inaccessible branch did not fail safely and independently")
	}
	h.query(service, "RESET ROLE", "idle")
	response = h.catalog(service, protocol.CatalogRequest{Kind: "columns", Schema: schema, Object: object})
	if response.Type != "query.result" || len(response.Rows) != 5 {
		t.Fatal("an inaccessible branch invalidated later metadata work")
	}
}
