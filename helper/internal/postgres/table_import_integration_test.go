func pgImportText(value string) protocol.CellValue {
	return protocol.CellValue{Kind: "text", Value: &value}
}
func pgImportBinary(value string) protocol.CellValue {
	return protocol.CellValue{Kind: "binary", Value: &value}
}
func pgDescribeImport(t *testing.T, f *changeFixture, table string) protocol.TableImportRequest {
	t.Helper()
	request := protocol.TableImportRequest{Schema: f.schema, Table: table}
	reply := tableImport(context.Background(), f.conn, protocol.Command{Type: "import.describe", TableImport: &request})
	if reply.Type != "import.describe.result" || !reply.Connected || reply.TransactionStatus != "idle" || reply.TableImport == nil {
		t.Fatalf("describe import failed category=%s state=%s", reply.Category, reply.SQLState)
	}
	request.Fingerprint = reply.TableImport.Fingerprint
	return request
}

func TestPostgresTableImportKeylessPreviewDefaultsAndAtomicRows(t *testing.T) {
	f := newChangeFixture(t)
	target := f.table("import_values")
	f.exec("CREATE TABLE " + target + " (id bigint GENERATED BY DEFAULT AS IDENTITY,label text NOT NULL UNIQUE,amount numeric(40,20),payload bytea,note text NOT NULL DEFAULT 'fallback',computed text GENERATED ALWAYS AS (upper(label)) STORED)")
	request := pgDescribeImport(t, f, "import_values")
	request.Columns = []string{"label", "amount", "payload"}
	request.Rows = [][]protocol.CellValue{{pgImportText("NULL"), pgImportText("12345678901234567890.12345678901234567890"), pgImportBinary("AP+A")}, {pgImportText(""), {Kind: "null"}, pgImportBinary("")}}
	preview := tableImport(context.Background(), f.conn, protocol.Command{Type: "import.preview", TableImport: &request})
	if preview.Type != "import.preview.result" || preview.TableImport.RowCount == nil || *preview.TableImport.RowCount != 2 || strings.Contains(preview.TableImport.SQL, "123456789") || f.scalar("SELECT count(*)::text FROM "+target) != "0" {
		t.Fatal("preview wrote rows or exposed values")
	}
	apply := tableImport(context.Background(), f.conn, protocol.Command{Type: "import.apply", TableImport: &request})
	if apply.Type != "import.apply.result" || apply.TableImport.RowCount == nil || *apply.TableImport.RowCount != 2 || f.scalar("SELECT count(*)::text FROM "+target) != "2" {
		t.Fatalf("keyless import failed category=%s state=%s", apply.Category, apply.SQLState)
	}
	if f.scalar("SELECT amount::text FROM "+target+" WHERE label='NULL'") != "12345678901234567890.12345678901234567890" || f.scalar("SELECT encode(payload,'hex') FROM "+target+" WHERE label='NULL'") != "00ff80" || f.scalar("SELECT note FROM "+target+" LIMIT 1") != "fallback" {
		t.Fatal("precise, binary or omitted-default value changed")
	}
	request.Rows = [][]protocol.CellValue{{pgImportText("rollback"), {Kind: "null"}, {Kind: "null"}}, {pgImportText("NULL"), {Kind: "null"}, {Kind: "null"}}}
	failed := tableImport(context.Background(), f.conn, protocol.Command{Type: "import.apply", TableImport: &request})
	if failed.Type != "error" || failed.OutcomeUnknown || failed.SQLNotExecuted || failed.TableImport == nil || *failed.TableImport.Row != 2 || f.scalar("SELECT count(*)::text FROM "+target) != "2" {
		t.Fatal("row failure committed a partial import")
	}
	f.exec("ALTER TABLE " + target + " ALTER COLUMN note SET DEFAULT 'changed'")
	stale := tableImport(context.Background(), f.conn, protocol.Command{Type: "import.preview", TableImport: &request})
	if stale.Type != "error" || stale.Category != "conflict" || !stale.SQLNotExecuted {
		t.Fatal("changed default bypassed fingerprint")
	}
}

func TestPostgresTableImportReadonlyPreviewCancellationAndUnknownCommit(t *testing.T) {
	f := newChangeFixture(t)
	target := f.table("import_lifecycle")
	f.exec("CREATE TABLE " + target + " (label text NOT NULL)")
	request := pgDescribeImport(t, f, "import_lifecycle")
	request.Columns = []string{"label"}
	request.Rows = [][]protocol.CellValue{{pgImportText("one")}}
	if _, err := f.conn.Exec(context.Background(), "SET default_transaction_read_only=on"); err != nil {
		t.Fatal("readonly setup")
	}
	_ = pgDescribeImport(t, f, "import_lifecycle")
	if reply := tableImport(context.Background(), f.conn, protocol.Command{Type: "import.preview", TableImport: &request}); reply.Type != "import.preview.result" {
		t.Fatal("readonly preview required a write lock")
	}
	if _, err := f.conn.Exec(context.Background(), "SET default_transaction_read_only=off"); err != nil {
		t.Fatal("readonly teardown")
	}
	f.exec("CREATE FUNCTION " + f.table("import_pause") + "() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN PERFORM pg_sleep(5); RETURN NEW; END $$; CREATE TRIGGER pause BEFORE INSERT ON " + target + " FOR EACH ROW EXECUTE FUNCTION " + f.table("import_pause") + "()")
	ctx, cancel := context.WithTimeout(context.Background(), 100*time.Millisecond)
	defer cancel()
	failed := tableImport(ctx, f.conn, protocol.Command{Type: "import.apply", TableImport: &request})
	if failed.Type != "error" || failed.Category != "timeout" || failed.OutcomeUnknown || !failed.Connected || failed.SQLNotExecuted || f.scalar("SELECT count(*)::text FROM "+target) != "0" {
		t.Fatal("cancelled import did not roll back")
	}
	f.exec("DROP TRIGGER pause ON " + target)
	unknown := tableImportWithCommit(context.Background(), f.conn, protocol.Command{Type: "import.apply", TableImport: &request}, func(ctx context.Context, conn *pgx.Conn) error {
		if _, err := conn.Exec(ctx, "COMMIT"); err != nil {
			return err
		}
		return io.ErrUnexpectedEOF
	})
	if unknown.Type != "error" || !unknown.OutcomeUnknown || unknown.Connected || f.scalar("SELECT count(*)::text FROM "+target) != "1" {
		t.Fatal("lost commit acknowledgement was retried or claimed rolled back")
	}
}

func TestPostgresTableImportBatchExceedsResultGridDisplayLimit(t *testing.T) {
	f := newChangeFixture(t)
	target := f.table("import_many")
	f.exec("CREATE TABLE " + target + " (label text NOT NULL)")
	request := pgDescribeImport(t, f, "import_many")
	request.Columns = []string{"label"}
	request.Rows = make([][]protocol.CellValue, 1001)
	for i := range request.Rows {
		request.Rows[i] = []protocol.CellValue{pgImportText("row")}
	}
	response := tableImport(context.Background(), f.conn, protocol.Command{Type: "import.apply", TableImport: &request})
	if response.Type != "import.apply.result" || response.TableImport.RowCount == nil || *response.TableImport.RowCount != 1001 || f.scalar("SELECT count(*)::text FROM "+target) != "1001" {
		t.Fatal("import incorrectly inherited the result-grid row limit")
	}
}
