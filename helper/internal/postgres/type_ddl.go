func typeResultFits(response protocol.Response) bool {
	encoded, err := json.Marshal(response)
	return err == nil && len(encoded)+4096 <= MaxResultBytes
}

func typeOperations(metadata TypeMetadata) (rename, enumChanges bool, limitations string) {
	rename = metadata.Extension == "" && metadata.Kind != "multirange"
	enumChanges = rename && metadata.Kind == "enum" && metadata.MembersComplete
	limitations = "Only type rename is supported here; structural changes require reviewed manual SQL."
	if metadata.Kind == "enum" {
		limitations = "Values can be appended or renamed. Removing or reordering enum values requires a separately designed migration."
		if !metadata.MembersComplete {
			limitations += " Enum labels exceed the metadata bound, so value previews are unavailable."
		}
	}
	if metadata.Extension != "" {
		limitations = "This type is managed by extension " + metadata.Extension + "; generated type changes are unavailable. " + limitations
	}
	if metadata.Kind == "multirange" {
		limitations = "This multirange is generated by its range type; generated changes are unavailable. Inspect and manage the owning range type."
	}
	return
}

func typeDefinition(metadata TypeMetadata) (definition *string, status, limitations, details string) {
	status = "complete"
	limitations = "Structural definition only; owner, grants and comments are not included."
	qualified := pgx.Identifier{metadata.Schema, metadata.Name}.Sanitize()
	var properties []string
	properties = append(properties, "Category: "+metadata.Kind)
	if metadata.Extension != "" {
		properties = append(properties, "Extension: "+metadata.Extension)
	}
	if !metadata.MembersComplete {
		status, limitations = "partial", "Type properties exceed the metadata bound. A complete CREATE definition is unavailable."
	} else {
		switch metadata.Kind {
		case "enum":
			labels := make([]string, len(metadata.EnumValues))
			for index, value := range metadata.EnumValues {
				labels[index] = postgresTextLiteral(value.Label)
			}
			definition = typeCell("CREATE TYPE " + qualified + " AS ENUM (" + strings.Join(labels, ", ") + ");")
		case "composite":
			var attributes []string
			for _, attribute := range metadata.Attributes {
				part := pgx.Identifier{attribute.Name}.Sanitize() + " " + attribute.NativeType
				if attribute.Collation != "" {
					part += " COLLATE " + attribute.Collation
				}
				attributes = append(attributes, part)
				if attribute.NotNull {
					status, limitations = "partial", "Composite attribute constraints are not reconstructed."
				}
			}
			if status == "complete" {
				definition = typeCell("CREATE TYPE " + qualified + " AS (" + strings.Join(attributes, ", ") + ");")
			}
		case "domain":
			ddl := "CREATE DOMAIN " + qualified + " AS " + metadata.BaseType
			if metadata.Collation != "" {
				ddl += " COLLATE " + metadata.Collation
			}
			if metadata.Default != nil {
				ddl += " DEFAULT " + *metadata.Default
			}
			if metadata.NotNull {
				ddl += " NOT NULL"
			}
			for _, constraint := range metadata.DomainConstraints {
				ddl += " CONSTRAINT " + pgx.Identifier{constraint.Name}.Sanitize() + " " + constraint.Definition
				if !constraint.Validated && !strings.Contains(strings.ToUpper(constraint.Definition), "NOT VALID") {
					ddl += " NOT VALID"
				}
			}
			definition = typeCell(ddl + ";")
		case "range", "multirange":
			status, limitations = "unavailable", "Range and generated multirange CREATE definitions are not reconstructed. Properties include support functions, operator class, collation and the paired type; manage them with reviewed manual SQL."
		default:
			status, limitations = "unavailable", "Base-type CREATE definitions require additional storage, I/O and support-function properties and are not reconstructed."
		}
	}
	switch metadata.Kind {
	case "enum":
		properties = append(properties, "Labels are ordered by PostgreSQL enumsortorder; no table rows are required.")
	case "domain":
		properties = append(properties, "Base type: "+metadata.BaseType)
		if metadata.Default == nil {
			properties = append(properties, "Default: none")
		} else {
			properties = append(properties, "Default: "+*metadata.Default)
		}
		if metadata.NotNull {
			properties = append(properties, "Nullable: no")
		} else {
			properties = append(properties, "Nullable: yes")
		}
		for _, constraint := range metadata.DomainConstraints {
			properties = append(properties, "Constraint "+pgx.Identifier{constraint.Name}.Sanitize()+": "+constraint.Definition)
		}
	case "composite":
		for _, attribute := range metadata.Attributes {
			part := "Attribute " + pgx.Identifier{attribute.Name}.Sanitize() + ": " + attribute.NativeType
			if attribute.Collation != "" {
				part += " COLLATE " + attribute.Collation
			}
			if attribute.NotNull {
				part += " NOT NULL"
			}
			properties = append(properties, part)
		}
	case "range", "multirange":
		if metadata.Range != nil {
			r := metadata.Range
			properties = append(properties, "Subtype: "+r.Subtype, "Operator class: "+r.Opclass,
				"Collation: "+r.Collation, "Canonical function: "+r.Canonical, "Subtype difference function: "+r.SubtypeDiff,
				"Range type: "+r.RangeName, "Generated multirange: "+r.MultirangeName)
		}
	case "base":
		if metadata.Base != nil {
			b := metadata.Base
			properties = append(properties, "Input function: "+b.Input, "Output function: "+b.Output,
				"Receive function: "+b.Receive, "Send function: "+b.Send, "Typmod input function: "+b.TypeModifierInput,
				"Typmod output function: "+b.TypeModifierOutput, "Analyze function: "+b.Analyze, "Subscript function: "+b.Subscript,
				fmt.Sprintf("Storage: length %d; by value %t; alignment %s; strategy %s", b.Length, b.ByValue, b.Alignment, b.Storage),
				fmt.Sprintf("Category: %s; preferred %t; delimiter %s; local element OID %d; local array OID %d", b.Category, b.Preferred, b.Delimiter, b.ElementOID, b.ArrayOID))
		}
	}
	if metadata.Collation != "" && metadata.Kind != "range" && metadata.Kind != "multirange" {
		properties = append(properties, "Collation: "+metadata.Collation)
	}
	if definition != nil && (metadata.Kind == "domain" || metadata.Kind == "composite") {
		status = "partial"
		limitations += " Referenced types, typmods, defaults and check expressions are rendered under the current session search_path. Review and qualify those references before recreating this type; this is reference SQL, not a portable complete definition."
	}
	if metadata.Extension != "" {
		if status == "complete" {
			status = "partial"
		}
		limitations = "Extension-managed type: recreate it through its extension. " + limitations
	}
	properties = append(properties, limitations)
	details = strings.Join(properties, "\n")
	return
}

func typeDDL(ctx context.Context, conn *pgx.Conn, command protocol.Command, metadata TypeMetadata, sink adapter.ResultSink) protocol.Response {
	change := command.Catalog.TypeChange
	if change == nil || !change.Valid() {
		return typeFailure(conn, command, "protocol", "Invalid type preview request.")
	}
	rename, enumChanges, _ := typeOperations(metadata)
	if change.Operation == "renameType" && !rename || change.Operation != "renameType" && !enumChanges {
		return typeFailure(conn, command, "unsupported", "This type does not support the requested generated change, or its properties are incomplete.")
	}
	if change.Operation == "renameType" {
		response := typeRead(ctx, conn, command, `SELECT EXISTS(SELECT 1 FROM pg_catalog.pg_type t JOIN pg_catalog.pg_namespace n ON n.oid=t.typnamespace WHERE n.nspname::text=$1::text AND t.typname::text=$2::text)::text`, typeParams(metadata.Schema, *change.NewName))
		if response.Type == "error" {
			return response
		}
		if len(response.Rows) != 1 || len(response.Rows[0]) != 1 || response.Rows[0][0] == nil || *response.Rows[0][0] != "false" {
			return typeFailure(conn, command, "validation", "A type with the requested destination name already exists or its name is unavailable.")
		}
	}
	sql, warnings, valid := typeChangeSQL(metadata, *change)
	if !valid {
		return typeFailure(conn, command, "validation", "The existing enum label is unavailable or the destination label already exists.")
	}
	if _, failure := typeHeader(ctx, conn, command); failure != nil {
		return *failure
	}
	return typeStringResult(ctx, conn, command, sink, []string{"sql", "warnings"}, []*string{typeCell(sql), typeCell(warnings)})
}

func typeChangeSQL(metadata TypeMetadata, change protocol.TypeChange) (sql, warnings string, valid bool) {
	if !change.Valid() {
		return "", "", false
	}
	rename, enumChanges, _ := typeOperations(metadata)
	qualified := pgx.Identifier{metadata.Schema, metadata.Name}.Sanitize()
	warnings = "Preview only; no changes have been executed. Open an SQL tab and review the normal execution assessment. PostgreSQL checks ownership and privileges at Run. Qualified-name SQL is not bound to this local OID after preview; refresh after external changes. Do not retry an uncertain DDL outcome automatically."
	switch change.Operation {
	case "renameType":
		if !rename {
			return "", "", false
		}
		keyword := "TYPE"
		if metadata.Kind == "domain" {
			keyword = "DOMAIN"
		}
		sql = "ALTER " + keyword + " " + qualified + " RENAME TO " + pgx.Identifier{*change.NewName}.Sanitize() + ";"
	case "addEnumValue", "renameEnumValue":
		if !enumChanges {
			return "", "", false
		}
		foundOld := false
		for _, existing := range metadata.EnumValues {
			if existing.Label == *change.Value {
				return "", "", false
			}
			if change.OldValue != nil && existing.Label == *change.OldValue {
				foundOld = true
			}
		}
		if change.Operation == "addEnumValue" {
			sql = "ALTER TYPE " + qualified + " ADD VALUE " + postgresTextLiteral(*change.Value) + ";"
			warnings += " The value is appended at the end. A newly added enum value cannot be used until its transaction commits; no transaction wrapper is generated."
		} else {
			if !foundOld {
				return "", "", false
			}
			sql = "ALTER TYPE " + qualified + " RENAME VALUE " + postgresTextLiteral(*change.OldValue) + " TO " + postgresTextLiteral(*change.Value) + ";"
			warnings += " Renaming preserves the existing enum order."
		}
	default:
		return "", "", false
	}
	return sql, warnings, true
}
