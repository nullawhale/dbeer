func TestStructureAdvancedGenerationNativeScopeLive(t *testing.T) {
	f := newChangeFixture(t)
	ctx := context.Background()
	var version int
	if f.conn.QueryRow(ctx, "SELECT pg_catalog.current_setting('server_version_num')::pg_catalog.int4").Scan(&version) != nil {
		t.Fatal("native version unavailable")
	}
	f.exec("CREATE TABLE " + f.table("scope_root") + "(id integer NOT NULL,base integer,derived integer GENERATED ALWAYS AS(base*2) STORED) PARTITION BY RANGE(id)")
	f.exec("CREATE TABLE " + f.table("scope_leaf") + " PARTITION OF " + f.table("scope_root") + " FOR VALUES FROM(0)TO(100)")
	f.exec("INSERT INTO " + f.table("scope_root") + "(id,base) VALUES(1,6)")
	for _, variant := range []struct {
		name, target string
		only         bool
	}{{"parentOnly", "scope_root", true}, {"parentRecursive", "scope_root", false}, {"leafOnly", "scope_leaf", true}, {"leafLocal", "scope_leaf", false}} {
		if version < 170000 {
			break
		} // SET EXPRESSION was added in PostgreSQL17.
		t.Run(variant.name, func(t *testing.T) {
			tx, err := f.conn.Begin(ctx)
			if err != nil {
				t.Fatal("native scope transaction unavailable")
			}
			defer structureRollback(tx)
			only := ""
			if variant.only {
				only = "ONLY "
			}
			_, err = tx.Exec(ctx, "ALTER TABLE "+only+f.table(variant.target)+" ALTER COLUMN derived SET EXPRESSION AS(base*3)")
			if err != nil {
				var native *pgconn.PgError
				if !errors.As(err, &native) || native.Code != "0A000" {
					t.Fatal("unexpected native generation error category")
				}
				t.Logf("native scope restriction SQLSTATE=%s routine=%s source=%s:%d", native.Code, native.Routine, native.File, native.Line)
				return
			}
			var value int
			if tx.QueryRow(ctx, "SELECT derived FROM "+f.table("scope_leaf")).Scan(&value) != nil {
				t.Fatal("native generated result unavailable")
			}
			expected := 18
			if variant.target == "scope_root" && variant.only {
				expected = 12
			}
			if value != expected {
				t.Fatal("native generation effect did not match its explicit scope")
			}
			t.Log("native generation action supported with verified row scope")
		})
	}
	for _, variant := range []struct {
		name, target string
		only         bool
	}{{"identityParentOnly", "scope_root", true}, {"identityParentRecursive", "scope_root", false}, {"identityLeafOnly", "scope_leaf", true}, {"identityLeafLocal", "scope_leaf", false}} {
		t.Run(variant.name, func(t *testing.T) {
			before, err := readStructure(ctx, f.conn, tableedit.Target{Schema: f.schema, Table: variant.target})
			if err != nil {
				t.Fatal("identity source metadata unavailable")
			}
			tx, err := f.conn.Begin(ctx)
			if err != nil {
				t.Fatal("native identity scope transaction unavailable")
			}
			defer structureRollback(tx)
			only := ""
			if variant.only {
				only = "ONLY "
			}
			_, err = tx.Exec(ctx, "ALTER TABLE "+only+f.table(variant.target)+" ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY")
			if err != nil {
				var native *pgconn.PgError
				if !errors.As(err, &native) || native.Code != "42P16" {
					t.Fatal("unexpected native identity restriction category")
				}
				t.Logf("native identity restriction SQLSTATE=%s routine=%s source=%s:%d", native.Code, native.Routine, native.File, native.Line)
				return
			}
			after, err := readStructure(ctx, tx, tableedit.Target{Schema: f.schema, Table: variant.target})
			if err != nil {
				t.Fatal("native identity result metadata unavailable")
			}
			c := tableedit.Condition{Operation: tableedit.Operation{Kind: "changeColumn", Change: &tableedit.ColumnChange{Name: "id", Identity: &tableedit.Identity{Kind: "byDefault"}}}}
			if err = pgAdvancedPreservationError(before, after, c); err != nil {
				t.Fatal(err)
			}
			var value int
			if tx.QueryRow(ctx, "SELECT id FROM "+f.table("scope_leaf")).Scan(&value) != nil || value != 1 {
				t.Fatal("native identity changed an existing value")
			}
			t.Log("native identity action supported with complete retained metadata and row scope")
		})
	}
	f.exec("CREATE TYPE " + f.table("scope_type") + " AS(id integer,base integer,derived integer)")
	tx, err := f.conn.Begin(ctx)
	if err != nil {
		t.Fatal("typed scope transaction unavailable")
	}
	defer structureRollback(tx)
	_, err = tx.Exec(ctx, "CREATE TABLE "+f.table("scope_typed")+" OF "+f.table("scope_type")+"(derived WITH OPTIONS GENERATED ALWAYS AS(base*2) STORED)")
	var native *pgconn.PgError
	if !errors.As(err, &native) || native.Code != "0A000" {
		t.Fatal("typed generation native restriction was not established")
	}
	t.Logf("native typed restriction SQLSTATE=%s routine=%s source=%s:%d", native.Code, native.Routine, native.File, native.Line)
}

func TestStructureAdvancedTypedIdentityStoreLive(t *testing.T) {
	f := newChangeFixture(t)
	ctx := context.Background()
	a := &Session{conn: f.conn}
	f.exec("CREATE TYPE " + f.table("identity_type") + " AS(id integer,payload text)")
	f.exec("CREATE TABLE " + f.table("identity_typed") + " OF " + f.table("identity_type") + "(id WITH OPTIONS NOT NULL)")
	f.exec("INSERT INTO " + f.table("identity_typed") + " VALUES(7,'retained')")
	pgAdvancedStoreApply(t, a, tableedit.Target{Schema: f.schema, Table: "identity_typed"}, tableedit.Draft{AuthoringVersion: 2, Columns: []tableedit.Column{}, Changes: []tableedit.ColumnChange{{Name: "id", Identity: &tableedit.Identity{Kind: "byDefault"}}}}, "ALTER TABLE ONLY "+f.table("identity_typed")+" ALTER COLUMN ")
	var id int
	if f.observer.QueryRow(ctx, "SELECT id FROM "+f.table("identity_typed")).Scan(&id) != nil || id != 7 {
		t.Fatal("typed identity changed existing data")
	}
}
