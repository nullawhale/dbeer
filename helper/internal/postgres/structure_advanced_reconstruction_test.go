			if err != nil {
				t.Fatal(err)
			}
			order := []string{}
			for _, c := range b.Columns {
				order = append(order, c.Name)
			}
			p, err := preparePGAdvancedReconstruction(b, tableedit.Draft{Reconstruct: true}, order)
